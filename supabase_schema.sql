ON public.master_shifts FOR SELECT USING (true);

CREATE POLICY "Allow public insert master_shifts" 
ON public.master_shifts FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public update master_shifts" 
ON public.master_shifts FOR UPDATE USING (true) WITH CHECK (true);

CREATE POLICY "Allow public delete master_shifts" 
